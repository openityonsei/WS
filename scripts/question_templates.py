def curated_for(item, subject):
    """문항의 큐레이션 표현 목록. Q1·Q2는 질병명을 끼워 넣는다."""
    # 질병명이 모두 받침으로 끝나서 '으로/은/을' 조사가 그대로 맞는다(2026 문진표 기준 16개 확인).
    d = (subject or "").split("(")[0].strip().replace("/", "이나 ")
    if d.startswith("기타"):
        d = "암을 포함한 기타 질환"
    key = "Q1" if item.startswith("Q1.") else "Q2" if item.startswith("Q2.") else item
    return [t.replace("{d}", d) for t in CURATED.get(key, [])]
